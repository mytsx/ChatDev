    @classmethod
    def _format_copilot_sub_agent(cls, fm: dict, body: str, cfg: SubAgentConfig) -> str:
        """Format for Copilot CLI: .github/agents/{name}.md"""
        lines = ["---"]
        lines.append(f"name: {fm.get('name', cfg.name)}")
        lines.append(f"description: {fm.get('description', cfg.description)}")
        tools = cfg.tools if cfg.tools else fm.get("tools", [])
        if isinstance(tools, list) and tools:
            lines.append(f"tools: {', '.join(tools)}")
        # Model mapping for Copilot
        model = cfg.model or fm.get("model")
        if model:
            copilot_model = cls.COPILOT_MODEL_MAP.get(model, model)
            lines.append(f"model: {copilot_model}")
        lines.append("---")
        lines.append("")
        lines.append(body)
        return "\n".join(lines)

    @staticmethod
    def _read_file(path: str) -> str:
        """Read file content as string."""
        with open(path) as f:
            return f.read()

    # ------------------------------------------------------------------
    # Utility helpers
    # ------------------------------------------------------------------

    @staticmethod
    def _get_hooks_dir() -> Path:
        """Get the .chatdev/hooks/ directory path."""
        return Path(__file__).resolve().parents[4] / ".chatdev" / "hooks"

    @staticmethod
    def _extract_keywords_from_prompt(prompt: str) -> List[str]:
        """Extract verdict keywords from a prompt hook's text.

        Looks for patterns like REVIEW_PASS, REVIEW_FAIL, QA_PASS, QA_FAIL, etc.
        """
        import re
        # Match uppercase words with underscores that look like verdict keywords
        pattern = r'\b([A-Z][A-Z0-9]*(?:_[A-Z0-9]+)+)\b'
        matches = re.findall(pattern, prompt)
        # Filter to likely verdict keywords (contain PASS, FAIL, APPROVE, etc.)
        verdict_indicators = {"PASS", "FAIL", "APPROVE", "REJECT", "EXIT"}
        keywords = []
        seen = set()
        for m in matches:
            if m in seen:
                continue
            parts = set(m.split("_"))
            if parts & verdict_indicators:
                keywords.append(m)
                seen.add(m)
        return keywords
